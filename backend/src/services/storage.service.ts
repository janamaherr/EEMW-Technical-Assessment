import { randomUUID } from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import { config } from '../config/env';

/** Multer writes incoming files here before they are validated and moved into place. */
export const tempUploadDir = path.join(config.uploadDir, '.tmp');

/** Storage key (relative to UPLOAD_DIR): `<documentId>/v<versionNumber>-<uuid>.<ext>`. */
export function buildVersionPath(documentId: string, versionNumber: number, ext: string): string {
  return path.posix.join(documentId, `v${versionNumber}-${randomUUID()}.${ext}`);
}

function toAbsolute(relativePath: string): string {
  const absolute = path.resolve(config.uploadDir, relativePath);
  // Defence in depth: stored paths are generated by us, but never escape UPLOAD_DIR.
  if (!absolute.startsWith(config.uploadDir + path.sep)) {
    throw new Error(`Refusing to access path outside UPLOAD_DIR: ${relativePath}`);
  }
  return absolute;
}

/** Moves a temp upload into permanent storage at `relativePath`. */
export async function moveIntoStorage(tempPath: string, relativePath: string): Promise<void> {
  const destination = toAbsolute(relativePath);
  await fs.mkdir(path.dirname(destination), { recursive: true });
  await fs.rename(tempPath, destination);
}

/**
 * Best-effort removal of a stored file (used to roll back when the database step fails), plus
 * its document folder if that is now empty.
 */
export async function removeFromStorage(relativePath: string): Promise<void> {
  const absolute = toAbsolute(relativePath);
  await fs.rm(absolute, { force: true }).catch(() => {});
  await fs.rmdir(path.dirname(absolute)).catch(() => {}); // fails harmlessly if not empty
}
